const fs = require("fs");
const path = require("path");

const blogDirectory = path.resolve(__dirname, "../public/blog");
const outputFile = path.resolve(__dirname, "../src/data/posts.generated.js");
const ignoredFiles = new Set(["README.md", "_TEMPLATE.md"]);

function readFrontmatter(fileName) {
  const filePath = path.join(blogDirectory, fileName);
  const source = fs.readFileSync(filePath, "utf8");
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);

  if (!match) throw new Error(`${fileName}: missing frontmatter`);

  const metadata = {};
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(":");
    if (separator === -1) continue;
    const key = line.slice(0, separator).trim();
    const rawValue = line.slice(separator + 1).trim();
    metadata[key] = rawValue.startsWith('"')
      ? JSON.parse(rawValue)
      : rawValue.replace(/^['"]|['"]$/g, "");
  }

  for (const key of ["slug", "title", "date", "readTime", "category", "excerpt"]) {
    if (!metadata[key]) throw new Error(`${fileName}: missing ${key}`);
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(metadata.slug)) {
    throw new Error(`${fileName}: slug must use lowercase letters, numbers, and hyphens`);
  }
  if (fileName !== `${metadata.slug}.md`) {
    throw new Error(`${fileName}: filename must be ${metadata.slug}.md`);
  }

  return {
    ...metadata,
    contentPath: `/blog/${fileName}`,
  };
}

const posts = fs
  .readdirSync(blogDirectory)
  .filter((fileName) => fileName.endsWith(".md") && !ignoredFiles.has(fileName))
  .map(readFrontmatter)
  .sort((a, b) => new Date(b.date) - new Date(a.date));

const slugs = new Set();
for (const post of posts) {
  if (slugs.has(post.slug)) throw new Error(`Duplicate blog slug: ${post.slug}`);
  slugs.add(post.slug);
}

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(
  outputFile,
  `// Generated by scripts/generate-blog-index.js. Edit the Markdown files in public/blog instead.\nexport const posts = ${JSON.stringify(posts, null, 2)};\n`,
);

console.log(`Indexed ${posts.length} blog posts.`);
